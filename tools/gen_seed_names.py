import re, pathlib
src = pathlib.Path("src/ConstEnums.h").read_text(encoding="utf-8")
block = re.search(r"enum SeedType\s*:\s*int32_t\s*\{(.*?)\};", src, re.S)
assert block, "SeedType enum not found"
names, value, entries = [], -1, []
for raw in block.group(1).split(","):
    line = raw.strip()
    if not line or line.startswith("//"):
        continue
    m = re.match(r"^([A-Z_0-9]+)\s*(?:=\s*(-?\d+))?$", line)
    if not m:
        continue
    name = m.group(1)
    value = int(m.group(2)) if m.group(2) else value + 1
    entries.append((name, value))

entries = [e for e in entries if e[1] >= 0]
entries.sort(key=lambda e: e[1])
print("entries:", len(entries), "max:", entries[-1])

h = """// SPDX-License-Identifier: LGPL-3.0-or-later
//
// SeedType <-> protocol name mapping. The lobby transfers cards by name so the
// Go server never has to duplicate the enum numbering; this table is generated
// from src/ConstEnums.h by tools/gen_seed_names.py.
#pragma once

#include <string>

#include "../ConstEnums.h"

namespace PvzpSeed
{
// Returns nullptr for unknown values.
const char* SeedTypeToName(SeedType theType);
// Accepts exactly the names produced by SeedTypeToName.
bool SeedNameToType(const std::string& theName, SeedType& theType);
}
"""
pathlib.Path("src/Lawn/System/SeedNames.h").write_text(h, encoding="utf-8", newline="\n")

lines = ["""// SPDX-License-Identifier: LGPL-3.0-or-later
// Generated by tools/gen_seed_names.py from src/ConstEnums.h. Do not edit.
#include "SeedNames.h"

#include <cstring>

namespace PvzpSeed
{
namespace
{
struct SeedNameEntry
{
	const char* mName;
	SeedType mType;
};

const SeedNameEntry SEED_NAMES[] = {"""]
for name, val in entries:
    lines.append('\t{"%s", %s},' % (name, name))
lines.append("""};

constexpr int SEED_NAME_COUNT = sizeof(SEED_NAMES) / sizeof(SEED_NAMES[0]);
}

const char* SeedTypeToName(SeedType theType)
{
	for (int i = 0; i < SEED_NAME_COUNT; i++)
	{
		if (SEED_NAMES[i].mType == theType)
		{
			return SEED_NAMES[i].mName;
		}
	}
	return nullptr;
}

bool SeedNameToType(const std::string& theName, SeedType& theType)
{
	for (int i = 0; i < SEED_NAME_COUNT; i++)
	{
		if (theName == SEED_NAMES[i].mName)
		{
			theType = SEED_NAMES[i].mType;
			return true;
		}
	}
	return false;
}
}
""")
pathlib.Path("src/Lawn/System/SeedNames.cpp").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print("written")
